import { test, expect } from '@playwright/test'

test('catalog, unavailable products, cart and demo checkout',async({page})=>{
  const errors:string[]=[];page.on('pageerror',error=>errors.push(error.message))
  await page.goto('/')
  await expect(page.locator('.product-card')).toHaveCount(12)
  await expect(page.locator('.product-card').filter({hasText:'Amoxicillin'}).getByRole('button',{name:'Currently unavailable'})).toBeDisabled()
  await page.getByRole('searchbox').fill('paracetamol')
  await expect(page.locator('.product-card')).toHaveCount(1)
  await page.getByRole('button',{name:'Add to cart',exact:true}).click()
  await page.getByRole('button',{name:/Open cart with 1 item/}).click()
  const dialog=page.getByRole('dialog')
  await dialog.getByRole('button',{name:'Continue to checkout'}).click()
  await dialog.getByLabel('Full name').fill('Demo Customer')
  await dialog.getByLabel('Mobile number').fill('9876543210')
  await dialog.getByLabel('House / building and street').fill('House 12, Example Street')
  await dialog.getByLabel('Locality').fill('Example locality')
  await dialog.getByLabel('PIN code').fill('505172')
  await dialog.getByRole('button',{name:'Try demo checkout'}).click()
  await expect(dialog.getByRole('heading',{name:'Demo checkout complete'})).toBeVisible()
  await expect(dialog.getByText(/No order was sent/)).toBeVisible()
  await expect.poll(()=>page.evaluate(()=>Object.values(localStorage).some(v=>v.includes('Demo Customer')||v.includes('9876543210')))).toBe(false)
  await dialog.getByRole('button',{name:'Continue shopping'}).click()
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
  expect(errors).toEqual([])
})

test('staff preview edits inventory and validates bulk CSV before saving',async({page})=>{
  await page.goto('/#admin')
  await page.getByRole('button',{name:'Explore admin preview'}).click()
  await page.getByRole('button',{name:'Edit Paracetamol',exact:true}).click()
  let dialog=page.getByRole('dialog')
  await dialog.getByLabel('Price per pack').fill('32.50')
  await dialog.getByLabel('Available quantity').fill('0')
  await dialog.getByRole('button',{name:'Save medicine'}).click()
  await expect(page.locator('.inventory-row').filter({hasText:'PM-001'})).toContainText('₹32.50')
  await page.getByRole('button',{name:'Bulk import'}).click()
  dialog=page.getByRole('dialog')
  const header='sku,name,composition,strength,pack_size,manufacturer,category,price,stock,prescription_required,active\n'
  await dialog.locator('input[type=file]').setInputFiles({name:'invalid.csv',mimeType:'text/csv',buffer:Buffer.from(header+'NEW-1,New medicine,,,10 tablets,Example Pharma,Medicines,-4,10,false,true')})
  await expect(dialog.getByText(/nothing will be saved/)).toBeVisible()
  await expect(dialog.getByRole('button',{name:/Confirm/})).toBeDisabled()
  await dialog.locator('input[type=file]').setInputFiles({name:'valid.csv',mimeType:'text/csv',buffer:Buffer.from(header+'NEW-1,New medicine,,,10 tablets,Example Pharma,Medicines,34.50,10,false,true')})
  await expect(dialog.getByText('Ready: 1 new products, 0 updates')).toBeVisible()
  await dialog.getByRole('button',{name:'Confirm 1 changes'}).click()
  await expect(page.locator('.inventory-row').filter({hasText:'NEW-1'})).toContainText('₹34.50')
  await page.reload()
  await page.getByRole('button',{name:'Explore admin preview'}).click()
  await expect(page.locator('.inventory-row').filter({hasText:'NEW-1'})).toBeVisible()
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
})
