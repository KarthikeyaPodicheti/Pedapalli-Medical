test('staff preview edits inventory and validates bulk CSV before saving',async({page})=>{
  await page.goto('/#admin')
  await page.getByRole('button',{name:'Explore admin preview'}).click()
  await page.getByRole('button',{name:'Edit Paracetamol',exact:true}).click()
  let dialog=page.getByRole('dialog')
  await dialog.getByLabel('Wholesale price').fill('32.50')
  await dialog.getByLabel('MRP').fill('40.00')
  await dialog.getByLabel('Available wholesale quantity').fill('0')
  await dialog.getByRole('button',{name:'Save medicine'}).click()
  await expect(page.locator('.inventory-row').filter({hasText:'PM-001'})).toContainText('₹32.50')
  await page.getByRole('button',{name:'Bulk import'}).click()
  dialog=page.getByRole('dialog')
  const header='sku,name,composition,strength,pack_size,manufacturer,category,price,mrp,stock,wholesale_unit,units_per_case,minimum_order_quantity,quantity_step,regulatory_class,prescription_required,pharmacist_approved,active\n'
  await dialog.locator('input[type=file]').setInputFiles({name:'invalid.csv',mimeType:'text/csv',buffer:Buffer.from(header+'NEW-1,New medicine,,,10 tablets,Example Pharma,Medicines,-4,40,10,pack,10,5,5,General trade,false,true,true')})
  await expect(dialog.getByText(/nothing will be saved/)).toBeVisible()
  await expect(dialog.getByRole('button',{name:/Confirm/})).toBeDisabled()
  await dialog.locator('input[type=file]').setInputFiles({name:'valid.csv',mimeType:'text/csv',buffer:Buffer.from(header+'NEW-1,New medicine,,,10 tablets,Example Pharma,Medicines,34.50,40,10,pack,10,5,5,General trade,false,true,true')})
  await expect(dialog.getByText('Ready: 1 new products, 0 updates')).toBeVisible()
  await dialog.getByRole('button',{name:'Confirm 1 changes'}).click()
  await expect(page.locator('.inventory-row').filter({hasText:'NEW-1'})).toContainText('₹34.50')
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
})
