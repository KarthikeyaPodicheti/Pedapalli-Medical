import { test, expect } from '@playwright/test'

test.beforeEach(async ({ page }) => {
  await page.goto('/')
  await page.evaluate(() => localStorage.clear())
  await page.reload()
})

test('verified buyer can create a valid wholesale demo order',async({page})=>{
  const errors:string[]=[];page.on('pageerror',error=>errors.push(error.message))
  await expect(page.locator('.product-card')).toHaveCount(12)
  await expect(page.getByRole('button',{name:/Sign in to view wholesale price/}).first()).toBeVisible()
  await page.getByRole('button',{name:/Explore approved buyer demo/}).click()
  await expect(page.getByRole('button',{name:/Sign out Srinivasa Medical/})).toBeVisible()
  await expect(page.getByRole('link',{name:'Staff portal'})).toHaveCount(0)
  await page.goto('/#admin')
  await expect(page.getByRole('heading',{name:'Buyer accounts cannot access the staff portal'})).toBeVisible()
  await expect(page.getByRole('button',{name:'Explore admin preview'})).toHaveCount(0)
  await page.getByRole('link',{name:'Return to buyer store'}).first().click()
  await page.getByRole('searchbox').fill('paracetamol')
  await expect(page.locator('.product-card')).toHaveCount(1)
  await page.getByRole('button',{name:'Add MOQ to cart'}).click()
  await page.getByRole('button',{name:/Open wholesale cart with 5 units/}).click()
  const dialog=page.getByRole('dialog')
  await expect(dialog).toHaveAccessibleName('Wholesale cart (5)')
  await expect(dialog).toContainText('MOQ 5')
  await dialog.getByRole('button',{name:'Review order request'}).click()
  await dialog.getByText('Store pickup').click()
  await dialog.getByText('Bank transfer').click()
  await dialog.getByRole('button',{name:'Submit demo order request'}).click()
  await expect(dialog.getByRole('heading',{name:'Demo order request simulated'})).toBeVisible()
  await expect(dialog.getByText(/not sent or saved/)).toBeVisible()
  await expect(dialog.getByText('₹110',{exact:true})).toBeVisible()
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
  expect(errors).toEqual([])
})

